CREATE FUNCTION public.get_campaign_data(p_user_id uuid, p_client_id uuid) RETURNS TABLE(campaign_name text, emails_sent integer, open_rate numeric, reply_rate numeric, positive_reply_rate numeric, leads_generated integer, week_1_leads integer, week_2_leads integer, week_3_leads integer, week_4_leads integer, last_synced timestamp with time zone)
    LANGUAGE plpgsql
    AS $$
declare
  v_agency_id uuid;
begin
  -- Resolve the agency that owns this user
  select id into v_agency_id
  from agency_details
  where user_id = p_user_id;

  -- Return latest campaign data from campaigns table
  -- Demo campaigns are stored in campaigns table, so same query handles both
  return query
    select
      c.name,
      c.emails_sent,
      c.open_rate,
      c.reply_rate,
      c.positive_reply_rate,
      c.leads_generated,
      c.week_1_leads,
      c.week_2_leads,
      c.week_3_leads,
      c.week_4_leads,
      c.last_synced
    from campaigns c
    where c.client_id = p_client_id
    order by c.created_at desc
    limit 1;
end;
$$;

