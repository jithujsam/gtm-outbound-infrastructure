-- Name: get_clients_with_campaign_count(uuid); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.get_clients_with_campaign_count(p_user_id uuid) RETURNS TABLE(id uuid, name text, slug text, status text, created_at timestamp with time zone, campaign_count bigint)
    LANGUAGE sql
    AS $$
  select
    c.id,
    c.name,
    c.slug,
    c.status,
    c.created_at,
    count(ca.id) as campaign_count
  from clients c
  left join campaigns ca on ca.client_id = c.id
  where c.agency_id = (select id from agency_details where user_id = p_user_id limit 1)
  group by c.id, c.name, c.slug, c.status, c.created_at
  order by c.created_at desc;
$$;

